function providerChainLabel(provider: ProviderId, settings: Settings): { configured: boolean; model: string; note: string } {
  if (provider === "ollama") {
    return { configured: true, model: settings.ollama_model, note: "Local · always free" };
  }
  if (provider === "openrouter") {
    return {
      configured: settings.openrouter_configured,
      model: settings.openrouter_model || "No model selected",
      note: settings.openrouter_configured ? "Configured · unverified" : "No key · unverified",
    };
  }
  if (provider === "gemini") {
    return {
      configured: settings.gemini_configured,
      model: settings.gemini_model,
      note: settings.gemini_configured ? "Configured · unverified" : "No key · unverified",
    };
  }
  return {
    configured: settings.groq_configured,
    model: settings.groq_model,
    note: settings.groq_configured ? "Configured · unverified" : "No key · unverified",
  };
}

